//! The drift check for the generated reference pages (`PR-DOC-003`): each test runs a generator of
//! the `tlilli` binary into a scratch directory and compares the result, file by file, with the
//! pages committed under `docs/reference/`. `scripts/gen_reference.sh` regenerates them, and
//! `scripts/gen_reference.sh --check` runs the same comparison from the shell.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use tempfile::TempDir;

/// Runs `tlilli` with `args` and then `out`, a path named `name` in a fresh temporary directory,
/// appended. The directory goes away when the returned guard drops.
fn generate(name: &str, args: &[&str]) -> (TempDir, PathBuf) {
    let dir = tempfile::tempdir().expect("a temporary directory");
    let out = dir.path().join(name);
    let output = tlilli(&[args, &[out.to_str().expect("a UTF-8 path")]].concat());
    assert!(output.status.success(), "tlilli {args:?}: {output:?}");
    (dir, out)
}

/// Runs the `tlilli` binary that cargo built for this test.
fn tlilli(args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_tlilli"))
        .args(args)
        .output()
        .expect("run the tlilli binary")
}

/// The text of a file, with CRLF folded to LF so a checkout that converts line endings compares.
fn read(path: &Path) -> String {
    fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("{}: {error}", path.display()))
        .replace("\r\n", "\n")
}

/// Asserts that `generated` is the text of `committed` (a path under `docs/reference/`).
fn assert_same_text(generated: &str, committed: &str) {
    let page = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../docs/reference")
        .join(committed);
    let stale = "run scripts/gen_reference.sh and commit the result";
    assert!(generated == read(&page), "{}: {stale}", page.display());
}

/// Asserts that `committed` (a directory under `docs/reference/`) holds exactly the files in
/// `generated`, with the same text.
fn assert_same_tree(generated: &Path, committed: &str) {
    let names = |dir: &Path| {
        let mut names: Vec<_> = fs::read_dir(dir)
            .unwrap_or_else(|error| panic!("{}: {error}", dir.display()))
            .map(|entry| entry.expect("a directory entry").file_name().into_string())
            .map(|name| name.expect("a UTF-8 file name"))
            .collect();
        names.sort();
        names
    };
    let committed_dir = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../docs/reference")
        .join(committed);
    assert_eq!(
        names(generated),
        names(&committed_dir),
        "{committed}: run scripts/gen_reference.sh"
    );
    for name in names(generated) {
        assert_same_text(
            &read(&generated.join(&name)),
            &format!("{committed}/{name}"),
        );
    }
}

#[test]
fn the_mcp_reference_matches_the_generator_and_says_it_is_generated() {
    let (_dir, out) = generate("mcp", &["mcp", "schema", "--markdown"]);
    assert_same_tree(&out, "mcp");
    for page in ["tools.md", "resources.md", "prompts.md"] {
        let text = fs::read_to_string(out.join(page)).unwrap();
        assert!(
            text.starts_with("<!-- Generated by `tlilli mcp schema --markdown`"),
            "{page}"
        );
    }
}

#[test]
fn the_json_schemas_match_the_generator_and_parse() {
    let (_dir, out) = generate("schemas", &["schema", "dump"]);
    assert_same_tree(&out, "schemas");
    for page in ["canonical.schema.json", "style-sheet.schema.json"] {
        let text = fs::read_to_string(out.join(page)).unwrap();
        let schema: serde_json::Value = serde_json::from_str(&text).unwrap();
        let id = format!("https://bioedca.github.io/Tlilli/reference/schemas/{page}");
        assert_eq!(schema["$id"], id.as_str());
        let comment = schema["$comment"].as_str().unwrap();
        assert!(
            comment.starts_with("Generated by `tlilli schema dump`"),
            "{page}"
        );
    }
}

#[test]
fn the_command_reference_matches_the_generator() {
    let output = tlilli(&["--help-markdown"]);
    assert!(output.status.success(), "{output:?}");
    let page = String::from_utf8(output.stdout).unwrap();
    assert_same_text(&page, "cli.md");
    assert!(page.starts_with("<!-- Generated by `tlilli --help-markdown`"));
    for command in [
        "tlilli mcp schema",
        "tlilli schema dump",
        "tlilli skills build",
    ] {
        assert!(
            page.contains(&format!("## `{command}`")),
            "no section for {command}"
        );
    }
    assert!(
        !page.contains("## `tlilli help`"),
        "clap's help subcommand is documented"
    );
    assert!(
        page.lines().all(|line| line == line.trim_end()),
        "trailing spaces"
    );
}

#[test]
fn the_skill_reference_matches_the_generator() {
    let skills = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../skills");
    let (_dir, out) = generate(
        "skills.md",
        &[
            "skills",
            "build",
            "--source",
            skills.to_str().unwrap(),
            "--docs",
        ],
    );
    let page = read(&out);
    assert_same_text(&page, "skills.md");
    assert!(page.starts_with("<!-- Generated by `tlilli skills build --docs`"));
}

#[test]
fn skills_build_refuses_a_source_that_already_holds_skills() {
    let dir = tempfile::tempdir().unwrap();
    let source = dir.path();
    fs::create_dir(source.join("tlilli-run")).unwrap();
    let out = source.join("skills.md");
    let source = source.to_str().unwrap();
    let output = tlilli(&[
        "skills",
        "build",
        "--source",
        source,
        "--docs",
        out.to_str().unwrap(),
    ]);
    assert_eq!(output.status.code(), Some(1));
    assert!(String::from_utf8_lossy(&output.stderr).contains("tlilli-run"));
    assert!(!out.exists(), "a refused build wrote the page");
}

#[test]
fn exit_codes_follow_fr_01_050() {
    assert_eq!(tlilli(&["--version"]).status.code(), Some(0));
    assert_eq!(tlilli(&["--help"]).status.code(), Some(0));
    // Usage errors, including an empty command line and a missing argument, are user errors.
    assert_eq!(tlilli(&[]).status.code(), Some(1));
    assert_eq!(tlilli(&["no-such-command"]).status.code(), Some(1));
    assert_eq!(tlilli(&["schema", "dump"]).status.code(), Some(1));
    assert_eq!(
        tlilli(&["--help-markdown", "schema", "dump", "x"])
            .status
            .code(),
        Some(1)
    );
    // So is an output directory that cannot be created, here because a file is in the way.
    let dir = tempfile::tempdir().unwrap();
    let blocker = dir.path().join("blocker");
    fs::write(&blocker, "").unwrap();
    let output = tlilli(&["schema", "dump", blocker.join("schemas").to_str().unwrap()]);
    assert_eq!(output.status.code(), Some(1));
    assert!(String::from_utf8_lossy(&output.stderr).starts_with("tlilli: "));
}
